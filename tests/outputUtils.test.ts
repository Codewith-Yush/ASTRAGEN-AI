import { describe, it, expect } from "vitest";
import {
  stripMarkdown,
  calculateReadingStats,
  generateHtmlDocument,
} from "../app/dashboard/content/_components/outputUtils";

describe("Output Utilities", () => {
  it("strips markdown tags into clean readable plain text", () => {
    const markdown = `# Main Title
## Subheading
This is **bold**, *italic*, and [a link](https://astragen.ai).
> This is a quote

\`\`\`typescript
const a = 10;
\`\`\`

- Bullet item 1
- Bullet item 2
- [x] Completed task`;

    const clean = stripMarkdown(markdown);
    expect(clean).not.toContain("#");
    expect(clean).not.toContain("**");
    expect(clean).not.toContain("*");
    expect(clean).not.toContain("[a link]");
    expect(clean).toContain("This is bold, italic, and a link.");
    expect(clean).toContain("This is a quote");
    expect(clean).toContain("Completed task");
  });

  it("calculates reading and speaking metrics accurately", () => {
    // 400 words
    const sampleText = Array(400).fill("word").join(" ");
    const stats = calculateReadingStats(sampleText);

    expect(stats.words).toBe(400);
    expect(stats.charsWithSpaces).toBe(sampleText.length);
    expect(stats.readingTimeMinutes).toBe(2); // 400 / 200 = 2 mins
    expect(stats.readingTimeString).toBe("2 mins read");
    expect(stats.speakingTimeString).toBe("4 mins speech"); // 400 / 130 = ~3.07 -> 4 mins
  });

  it("handles empty and whitespace-only text gracefully", () => {
    const emptyStats = calculateReadingStats("");
    expect(emptyStats.words).toBe(0);
    expect(emptyStats.charsWithSpaces).toBe(0);
    expect(emptyStats.readingTimeString).toBe("< 1 min read");
    expect(emptyStats.speakingTimeString).toBe("< 1 min speech");
  });

  it("generates a well-formatted standalone HTML document", () => {
    const htmlDoc = generateHtmlDocument("Test Document", "<p>Hello world</p>");
    expect(htmlDoc).toContain("<!DOCTYPE html>");
    expect(htmlDoc).toContain("<title>Test Document</title>");
    expect(htmlDoc).toContain("<p>Hello world</p>");
    expect(htmlDoc).toContain("Generated by Astragen AI");
  });
});
